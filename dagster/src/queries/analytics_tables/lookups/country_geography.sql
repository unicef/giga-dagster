--   - One row per Giga Maps country; iso3_code is unique.
--   - Names must be printable ASCII: all_school_master is partitioned by country,
--     and Hive partition values reject accented characters (HIVE_INVALID_PARTITION_VALUE,
--     2026-10-29). So 'Cote d''Ivoire', 'Reunion', 'Aland Islands', 'Saint Barthelemy', 'Curacao'.
--   - Namibia's ISO2 is the text 'NA', never NULL (CSV loaders read NA as missing).
--   - Uninhabited territories (ATA, BVT, ATF, HMD, SGS) have NULL regions.
--
-- How to run (manual, Trino UI / SQL Lab on prod, one statement per run):
--   1. Back up the live table (CREATE TABLE <your_schema>.country_geography_bak_<date> AS SELECT * ...).
--   2. DROP TABLE custom_dataset.country_geography; then make sure the ADLS folder
--      warehouse/country_geography is empty (Trino's DROP does not delete it, and a
--      non-empty location makes the CREATE fail: "Target location cannot contain any files").
--   3. Run this script with {AZURE_BLOB_CONNECTION_URI} replaced by the prod storage URI.
--   4. Rebuild daily/all_school_master, then daily/all_gigameter_funnelsummary (in that order).
--
-- Last Updated:    2026-10-29 / Luke Stringer
-- ==============================================================================

